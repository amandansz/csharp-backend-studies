public class Variaveis
{
    public static void Executar()
    {
        int numero = 7;
        Console.WriteLine(numero); // declara variável inteira e armazena o valor 7

        string nome = "Amanda";
        Console.WriteLine(nome); // declara variável string e armazena o valor "Amanda"

        bool estaChovendo = true; // declara variável do tipo booleano e armazena o valor true
        Console.WriteLine(estaChovendo);

        double pi = 3.14; // declara variável do tipo double e armazena o valor 3.14
        Console.WriteLine(pi);
              
        
    }
}